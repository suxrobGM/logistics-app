using Logistics.Domain.Entities;
using Logistics.Shared.Models;
using Riok.Mapperly.Abstractions;

namespace Logistics.Mappings;

[Mapper]
public static partial class DocumentMapper
{
    // Base -> DTO (polymorphic dispatcher; not generated)
    // Note: DeliveryDocument must be checked before LoadDocument since it derives from LoadDocument
    public static DocumentDto ToDto(this Document src)
    {
        return src switch
        {
            DeliveryDocument dd => dd.ToDeliveryDocumentDto(),
            LoadDocument ld => ld.ToLoadDocumentDto(),
            EmployeeDocument ed => ed.ToEmployeeDocumentDto(),
            TruckDocument td => td.ToTruckDocumentDto(),
            _ => throw new NotSupportedException($"Unsupported document type: {src.GetType().Name}")
        };
    }

    // Collection helpers (use the polymorphic dispatcher)
    public static IEnumerable<DocumentDto> ToDto(this IEnumerable<Document> src) => src.Select(ToDto);

    // Derived -> DTO (generated by Mapperly)
    // Map DeliveryDocument (includes LoadId from parent and all POD/BOL metadata)
    [MapperIgnoreSource(nameof(DeliveryDocument.DomainEvents))]
    [MapperIgnoreSource(nameof(DeliveryDocument.OwnerType))]
    [MapperIgnoreSource(nameof(DeliveryDocument.UploadedBy))]
    [MapperIgnoreSource(nameof(DeliveryDocument.CreatedBy))]
    [MapperIgnoreSource(nameof(DeliveryDocument.UpdatedBy))]
    [MapperIgnoreSource(nameof(DeliveryDocument.Load))]
    [MapperIgnoreSource(nameof(DeliveryDocument.TripStop))]
    [MapperIgnoreTarget(nameof(DocumentDto.EmployeeId))]
    [MapperIgnoreTarget(nameof(DocumentDto.TruckId))]
    [MapProperty(nameof(DeliveryDocument.LoadId), nameof(DocumentDto.LoadId))]
    private static partial DocumentDto ToDeliveryDocumentDto(this DeliveryDocument src);

    // Derived -> DTO (generated by Mapperly)
    // Map LoadDocument.LoadId -> DocumentDto.LoadId
    [MapperIgnoreSource(nameof(LoadDocument.DomainEvents))]
    [MapperIgnoreSource(nameof(LoadDocument.OwnerType))]
    [MapperIgnoreSource(nameof(LoadDocument.UploadedBy))]
    [MapperIgnoreSource(nameof(LoadDocument.CreatedBy))]
    [MapperIgnoreSource(nameof(LoadDocument.UpdatedBy))]
    [MapperIgnoreSource(nameof(LoadDocument.Load))]
    [MapperIgnoreTarget(nameof(DocumentDto.EmployeeId))]
    [MapperIgnoreTarget(nameof(DocumentDto.TruckId))]
    [MapperIgnoreTarget(nameof(DocumentDto.TripStopId))]
    [MapperIgnoreTarget(nameof(DocumentDto.RecipientName))]
    [MapperIgnoreTarget(nameof(DocumentDto.RecipientSignature))]
    [MapperIgnoreTarget(nameof(DocumentDto.CaptureLatitude))]
    [MapperIgnoreTarget(nameof(DocumentDto.CaptureLongitude))]
    [MapperIgnoreTarget(nameof(DocumentDto.CapturedAt))]
    [MapperIgnoreTarget(nameof(DocumentDto.Notes))]
    [MapperIgnoreTarget(nameof(DocumentDto.UnableToSignReason))]
    [MapProperty(nameof(LoadDocument.LoadId), nameof(DocumentDto.LoadId))]
    private static partial DocumentDto ToLoadDocumentDto(this LoadDocument src);

    // Derived -> DTO (generated by Mapperly)
    // Map EmployeeDocument.EmployeeId -> DocumentDto.EmployeeId
    [MapperIgnoreSource(nameof(EmployeeDocument.DomainEvents))]
    [MapperIgnoreSource(nameof(EmployeeDocument.OwnerType))]
    [MapperIgnoreSource(nameof(EmployeeDocument.UploadedBy))]
    [MapperIgnoreSource(nameof(EmployeeDocument.CreatedBy))]
    [MapperIgnoreSource(nameof(EmployeeDocument.UpdatedBy))]
    [MapperIgnoreSource(nameof(EmployeeDocument.Employee))]
    [MapperIgnoreTarget(nameof(DocumentDto.LoadId))]
    [MapperIgnoreTarget(nameof(DocumentDto.TruckId))]
    [MapperIgnoreTarget(nameof(DocumentDto.TripStopId))]
    [MapperIgnoreTarget(nameof(DocumentDto.RecipientName))]
    [MapperIgnoreTarget(nameof(DocumentDto.RecipientSignature))]
    [MapperIgnoreTarget(nameof(DocumentDto.CaptureLatitude))]
    [MapperIgnoreTarget(nameof(DocumentDto.CaptureLongitude))]
    [MapperIgnoreTarget(nameof(DocumentDto.CapturedAt))]
    [MapperIgnoreTarget(nameof(DocumentDto.Notes))]
    [MapperIgnoreTarget(nameof(DocumentDto.UnableToSignReason))]
    [MapProperty(nameof(EmployeeDocument.EmployeeId), nameof(DocumentDto.EmployeeId))]
    private static partial DocumentDto ToEmployeeDocumentDto(this EmployeeDocument src);

    // Derived -> DTO (generated by Mapperly)
    // Map TruckDocument.TruckId -> DocumentDto.TruckId
    [MapperIgnoreSource(nameof(TruckDocument.DomainEvents))]
    [MapperIgnoreSource(nameof(TruckDocument.OwnerType))]
    [MapperIgnoreSource(nameof(TruckDocument.UploadedBy))]
    [MapperIgnoreSource(nameof(TruckDocument.CreatedBy))]
    [MapperIgnoreSource(nameof(TruckDocument.UpdatedBy))]
    [MapperIgnoreSource(nameof(TruckDocument.Truck))]
    [MapperIgnoreTarget(nameof(DocumentDto.LoadId))]
    [MapperIgnoreTarget(nameof(DocumentDto.EmployeeId))]
    [MapperIgnoreTarget(nameof(DocumentDto.TripStopId))]
    [MapperIgnoreTarget(nameof(DocumentDto.RecipientName))]
    [MapperIgnoreTarget(nameof(DocumentDto.RecipientSignature))]
    [MapperIgnoreTarget(nameof(DocumentDto.CaptureLatitude))]
    [MapperIgnoreTarget(nameof(DocumentDto.CaptureLongitude))]
    [MapperIgnoreTarget(nameof(DocumentDto.CapturedAt))]
    [MapperIgnoreTarget(nameof(DocumentDto.Notes))]
    [MapperIgnoreTarget(nameof(DocumentDto.UnableToSignReason))]
    [MapProperty(nameof(TruckDocument.TruckId), nameof(DocumentDto.TruckId))]
    private static partial DocumentDto ToTruckDocumentDto(this TruckDocument src);

    private static DateTime Map(DateTimeOffset value) => value.UtcDateTime;

    private static DateTime? Map(DateTimeOffset? value) => value?.UtcDateTime;
}
