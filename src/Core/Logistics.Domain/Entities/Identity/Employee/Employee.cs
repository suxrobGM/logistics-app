using Logistics.Domain.Core;
using Logistics.Domain.Primitives;
using Logistics.Domain.Primitives.Enums;
using Logistics.Domain.Primitives.ValueObjects;

namespace Logistics.Domain.Entities;

public class Employee : Entity, ITenantEntity
{
    public required string Email { get; set; }
    public required string FirstName { get; set; }
    public required string LastName { get; set; }
    public string? PhoneNumber { get; set; }

    /// <summary>
    /// Personal address. Required for Stripe Connect onboarding when the employee's country differs
    /// from the tenant's; otherwise the tenant's company address is used as a fallback.
    /// </summary>
    public Address? Address { get; set; }

    public required decimal Salary { get; set; }
    public SalaryType SalaryType { get; set; } = SalaryType.None;
    public EmployeeStatus Status { get; set; } = EmployeeStatus.Active;

    /// <summary>
    ///     Share-of-gross pay is computed on the linehaul without the fuel surcharge.
    /// </summary>
    public bool PayExcludesFuelSurcharge { get; set; }

    /// <summary>
    ///     Share-of-gross pay is computed without accessorials (detention, lumper, ...).
    /// </summary>
    public bool PayExcludesAccessorials { get; set; }

    /// <summary>
    ///     Fuel card purchases on trucks this employee is the main driver of are deducted from their settlements.
    /// </summary>
    public bool DeductFuelCardCharges { get; set; }

    /// <summary>
    ///     Deductions taken from every settlement (truck lease, insurance, ELD fee, escrow).
    /// </summary>
    public virtual List<RecurringDeduction> RecurringDeductions { get; set; } = [];

    /// <summary>
    ///     When employee joined to this tenant
    /// </summary>
    public DateTime JoinedDate { get; set; } = DateTime.UtcNow;

    /// <summary>
    ///     User's device token generated by the Firebase
    /// </summary>
    public string? DeviceToken { get; set; }

    public virtual List<EmployeeDocument> Documents { get; set; } = [];

    /// <summary>
    ///     Driver licenses (history). A driver can hold multiple licenses across jurisdictions
    ///     or accumulated renewals.
    /// </summary>
    public virtual List<DriverLicense> Licenses { get; set; } = [];

    /// <summary>
    ///     Dispatched loads by dispatchers
    /// </summary>
    public virtual List<Load> DispatchedLoads { get; } = [];

    /// <summary>
    ///     Stripe Connected Account ID for receiving payroll payouts via bank transfer.
    /// </summary>
    public string? StripeConnectedAccountId { get; set; }

    public virtual List<PayrollInvoice> PayrollInvoices { get; set; } = [];

    /// <summary>
    ///     Time entries for hourly employees
    /// </summary>
    public virtual List<TimeEntry> TimeEntries { get; set; } = [];

    /// <summary>
    ///     User tenant role
    /// </summary>
    public Guid? RoleId { get; set; }
    public virtual TenantRole? Role { get; set; }

    public string GetFullName()
    {
        return string.Join(" ", FirstName, LastName);
    }

    /// <summary>The part of a load's revenue share-of-gross pay is computed on, after the pay exclusions.</summary>
    public decimal PayableRevenue(decimal linehaul, decimal fuelSurcharge, decimal accessorials) =>
        linehaul + (PayExcludesFuelSurcharge ? 0 : fuelSurcharge) + (PayExcludesAccessorials ? 0 : accessorials);

    /// <summary>Pay earned on the given loads by a per-load salary type; 0 for period-paid types.</summary>
    public decimal PayForLoads(IReadOnlyCollection<LoadPayBasis> loads, DistanceUnit unit)
    {
        var rate = Salary;
        return SalaryType switch
        {
            SalaryType.ShareOfGross =>
                loads.Sum(l => PayableRevenue(l.Linehaul, l.FuelSurcharge, l.Accessorials)) * rate,
            SalaryType.RatePerDistance => unit.FromMeters(loads.Sum(l => l.Distance)).ToDecimal() * rate,
            SalaryType.PerLoad => loads.Count * rate,
            SalaryType.PerStop => loads.Sum(l => l.DepartedStops) * rate,
            _ => 0m
        };
    }

    /// <summary>Pay for a period by a Weekly, Monthly or Hourly type, or the base pay of an untyped salary; 0 for per-load types.</summary>
    public decimal PayForPeriod(decimal weeks, decimal months, decimal hours)
    {
        var rate = Salary;
        return SalaryType switch
        {
            SalaryType.Weekly => weeks * rate,
            SalaryType.Monthly => months * rate,
            SalaryType.Hourly => hours * rate,
            SalaryType.ShareOfGross or SalaryType.RatePerDistance or SalaryType.PerLoad or SalaryType.PerStop => 0m,
            _ => rate
        };
    }

    /// <summary>Names what <see cref="PayableRevenue"/> covers, for the gross pay line of a settlement.</summary>
    public string PayableRevenueBasis() => (PayExcludesFuelSurcharge, PayExcludesAccessorials) switch
    {
        (true, true) => "linehaul",
        (true, false) => "linehaul and accessorials",
        (false, true) => "linehaul and fuel surcharge",
        _ => "gross revenue"
    };

    public static Employee CreateEmployeeFromUser(
        User user,
        decimal salary = 0,
        SalaryType salaryType = SalaryType.None)
    {
        var newEmployee = new Employee
        {
            Id = user.Id,
            Email = user.Email!,
            FirstName = user.FirstName,
            LastName = user.LastName,
            PhoneNumber = user.PhoneNumber,
            Salary = salary,
            SalaryType = salaryType
        };

        return newEmployee;
    }
}
